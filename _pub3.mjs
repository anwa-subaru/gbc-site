import { chromium } from 'playwright';
const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
const p = b.contexts()[0].pages()[0];
await p.goto('https://github.com/new', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(2500);
await p.fill('#repository-name-input', 'gbc-site');
await p.waitForTimeout(300);
const desc = p.locator('#_r_c_');
if (await desc.count()) await desc.fill('Girls Band Cry 粉丝站（Astro 静态站，含三语 UI / 逐字歌词 / 播放器）');
await p.waitForTimeout(500);
console.log('可见性:', await p.evaluate(() => [...document.querySelectorAll('button')].map(e => e.innerText.trim()).filter(t => /Public|Private/.test(t))));
await p.screenshot({ path: '/root/gh-login/27-before-create.png' });
await p.getByRole('button', { name: /^Create repository$/ }).first().click();
await p.waitForTimeout(8000);
console.log('建仓后 URL:', p.url());
console.log('结果:', (await p.locator('body').innerText()).replace(/\s+/g, ' ').trim().slice(0, 260));
await p.screenshot({ path: '/root/gh-login/28-created.png' });
process.exit(0);
